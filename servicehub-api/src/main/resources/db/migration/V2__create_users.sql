-- V2: usuarios (Mapa, secao 3).
-- Decisoes: exclusao logica (is_active), e-mail sempre minusculo (CHECK) e unico,
-- papel restrito por CHECK (segunda linha de defesa; a primeira e a aplicacao).
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100)  NOT NULL,
    email         VARCHAR(255)  NOT NULL,
    password_hash VARCHAR(255)  NOT NULL,
    role          VARCHAR(20)   NOT NULL DEFAULT 'CLIENT',
    phone         VARCHAR(20),
    bio           ${textType},
    avatar_url    VARCHAR(500),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_lower CHECK (email = LOWER(email)),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'PROVIDER', 'CLIENT'))
);
